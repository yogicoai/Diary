function utcDay(dateKey: string): number {
  const [y, m, d] = dateKey.split("-").map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / 86400000);
}

export function weekdayOf(dateKey: string): number {
  return (((utcDay(dateKey) + 4) % 7) + 7) % 7; // 1970-01-01 은 목요일(4)
}

export const WEEKDAY_NAMES = ["일", "월", "화", "수", "목", "금", "토"];

/** 선생님이 안 걸어 둔 날의 숙제 */
export function builtInTopic(dateKey: string): Topic {
  if (dateKey < NEW_TOPICS_FROM) return { date: dateKey, text: topicOf(dateKey), kind: "legacy", subject: null, note: null };
  const special = SPECIAL_DAYS[dateKey.slice(5)];
  if (special) return { date: dateKey, text: special[0], kind: "special", subject: "그날만의 숙제", note: special[1] };
  const group = WEEKDAY_TOPICS[weekdayOf(dateKey)];
  const week = Math.floor((utcDay(dateKey) + 3) / 7); // 월요일에 바뀌는 주 번호
  const [text, note] = group.list[((week % group.list.length) + group.list.length) % group.list.length];
  return { date: dateKey, text, kind: "weekday", subject: group.subject, note };
}
