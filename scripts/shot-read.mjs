import puppeteer from "puppeteer-core";
import fs from "node:fs";
const edge = ["C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", "C:/Program Files/Microsoft/Edge/Application/msedge.exe"].find((p) => fs.existsSync(p));
const browser = await puppeteer.launch({ executablePath: edge, headless: true, args: ["--autoplay-policy=no-user-gesture-required"] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto("http://localhost:6900/", { waitUntil: "networkidle0" });
await page.evaluate(() => { localStorage.setItem("chamjal.aiConsent", "yes"); localStorage.setItem("chamjal.readVoice", "boy"); });
await page.goto("http://localhost:6900/", { waitUntil: "networkidle0" });
await page.evaluate(() => document.fonts.ready);
await page.click('.weather button[aria-label="좋았어"]');
await page.type("#title", "떡볶이 먹은 날");
await page.focus(".manuscript textarea");
await page.keyboard.sendCharacter("퇴근하고 친구랑 떡볶이를 먹었다. 너무 맛있어서 웃음이 났다.");
await page.evaluate(() => document.querySelector(".btn:not(:disabled)")?.click());
await page.waitForSelector(".read-aloud", { timeout: 20000 });
await new Promise((r) => setTimeout(r, 2500));
const line = await page.$eval(".teacher-line", (e) => e.textContent);
console.log("선생님:", line);
const ra = await page.$(".read-aloud");
await ra.evaluate((e) => e.scrollIntoView({ block: "center" }));
await page.screenshot({ path: "shots/read-aloud.png" });
await page.click(".ra-play");
await page.waitForSelector(".ra-play.playing", { timeout: 15000 }).catch(() => console.log("재생 상태로 안 바뀜"));
await page.screenshot({ path: "shots/read-aloud-playing.png" });
console.log("상태:", await page.$eval(".ra-play", (e) => e.className + " / " + e.textContent));
console.log("오류:", errors.length ? errors : "없음");
await browser.close();
